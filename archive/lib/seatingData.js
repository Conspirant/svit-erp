function expandUsnRange(str) {
  if (!str.includes("-")) return [str];
  const [start, end] = str.split("-");
  const prefix = start.substring(0, 7); // e.g. "1VA25CS"
  const startNum = parseInt(start.substring(7), 10);
  const endNum = parseInt(end.substring(7), 10);
  
  if (isNaN(startNum) || isNaN(endNum)) return [str];

  const results = [];
  for (let i = startNum; i <= endNum; i++) {
    results.push(`${prefix}${i.toString().padStart(3, "0")}`);
  }
  return results;
}

export function getSeatingInfo(usn) {
  if (!usn) return null;
  const upperUsn = usn.toUpperCase().trim();
  
  for (const roomData of seatingRaw) {
    let seatIndex = 1;
    for (const rangeStr of roomData.range) {
      const expanded = expandUsnRange(rangeStr);
      const idx = expanded.indexOf(upperUsn);
      if (idx !== -1) {
        return {
          room: roomData.room,
          branch: roomData.branch,
          semester: roomData.semester,
          seatNumber: seatIndex + idx
        };
      }
      seatIndex += expanded.length;
    }
  }
  return null;
}
